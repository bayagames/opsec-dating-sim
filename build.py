import glob
t=open('src/template.html').read()
js='\n'.join(open(f).read() for f in sorted(glob.glob('src/*.js')))
# character art (art/chars/<look>.js, made by tools/import.html or tools/artprep.js): a tag for every look in the
# game, so a new file dropped into art/chars works without rebuilding; looks with no file yet are simply skipped
import re
looks=re.findall(r"^ ([a-z0-9]+):\{name:'([^']*)'",open('src/01_engine.js').read(),re.M)
art=''.join(f'<script src="art/chars/{k}.js" onerror="this.remove()"></script>\n' for k,_ in looks)
t=t.replace('<script src="vendor/three.bundle.js"></script>\n','<script src="vendor/three.bundle.js"></script>\n'+art)
open('tools/looks.js','w').write('/* generated by build.py: every look in the game (id, name) */\nconst LOOKS='+repr([list(l) for l in looks]).replace("'",'"')+';\n')
open('index.html','w').write(t.replace('/*JS*/',js))
open('/tmp/all.js','w').write('{'+js+'}')
