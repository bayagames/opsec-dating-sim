// Turns character-creator SVG exports into game art.
// Usage: node tools/artprep.js <look id> n=<file.svg> h=<file.svg> o=... s=... b=... a=... d=...
//   expressions: n neutral (required), h happy, o surprised, s half-lidded, b worried/blush, a angry, d teary
// Every export must come from the same creator canvas (2560x5120, feet on the same line), so heights carry over.
// Writes art/chars/<id>.js: one full body (from the neutral) plus, for each other expression, only the rectangle of
// the face that changes. Images are embedded as data URLs so the 3D world can use them even when index.html is
// opened straight from disk. Then run python3 build.py (it adds a <script> tag for every file in art/chars).
const {chromium}=require('playwright');const fs=require('fs'),path=require('path');
const [id,...pairs]=process.argv.slice(2);
if(!id||!pairs.length){console.log('usage: node tools/artprep.js <id> n=<neutral.svg> h=<happy.svg> ...');process.exit(1)}
const files={};for(const p of pairs){const[k,f]=p.split('=');files[k]=fs.readFileSync(f,'utf8')}
if(!files.n){console.log('a neutral (n=...) is required');process.exit(1)}
(async()=>{const b=await chromium.launch();const pg=await b.newPage();
 const out=await pg.evaluate(async files=>{
  const W=2560,H=5120;
  const draw=async svg=>{const url=URL.createObjectURL(new Blob([svg],{type:'image/svg+xml'}));const img=new Image();img.src=url;await img.decode();
   const c=document.createElement('canvas');c.width=W;c.height=H;c.getContext('2d').drawImage(img,0,0,W,H);URL.revokeObjectURL(url);return c};
  const C={};for(const k in files)C[k]=await draw(files[k]);
  const px=k=>C[k].getContext('2d').getImageData(0,0,W,H).data;
  const N=px('n');
  // the figure: everything with some opacity
  let x0=W,y0=H,x1=0,y1=0;for(let y=0;y<H;y++)for(let x=0;x<W;x++){if(N[(y*W+x)*4+3]>8){if(x<x0)x0=x;if(x>x1)x1=x;if(y<y0)y0=y;if(y>y1)y1=y}}
  const m=16,body=[Math.max(0,x0-m),Math.max(0,y0-m),0,0];body[2]=Math.min(W,x1+m)-body[0];body[3]=Math.min(H,y1+m)-body[1];
  // the part of the face that changes between expressions
  let f0=W,g0=H,f1=0,g1=0;
  for(const k in C){if(k==='n')continue;const D=px(k);for(let y=y0;y<=y1;y++)for(let x=x0;x<=x1;x++){const i=(y*W+x)*4;if(Math.abs(D[i]-N[i])+Math.abs(D[i+1]-N[i+1])+Math.abs(D[i+2]-N[i+2])+Math.abs(D[i+3]-N[i+3])>12){if(x<f0)f0=x;if(x>f1)f1=x;if(y<g0)g0=y;if(y>g1)g1=y}}}
  const fm=12,face=f1>f0?[f0-fm,g0-fm,f1-f0+2*fm,g1-g0+2*fm]:null;
  const crop=(k,r)=>{const c=document.createElement('canvas');c.width=r[2];c.height=r[3];c.getContext('2d').drawImage(C[k],r[0],r[1],r[2],r[3],0,0,r[2],r[3]);return c.toDataURL('image/webp',.9)};
  const ex={};for(const k in C)if(k!=='n'&&face)ex[k]=crop(k,face);
  return{body,face,top:y0,foot:y1,cx:Math.round((x0+x1)/2),img:crop('n',body),ex}},files);
 await b.close();
 const dir=path.join(__dirname,'..','art','chars');fs.mkdirSync(dir,{recursive:true});
 const meta={body:out.body,face:out.face,top:out.top,foot:out.foot,cx:out.cx};
 fs.writeFileSync(path.join(dir,id+'.js'),`/* ${id}: generated by tools/artprep.js from character-creator exports. Do not edit by hand. */\n(window.ART=window.ART||{})[${JSON.stringify(id)}]=Object.assign(${JSON.stringify(meta)},{img:${JSON.stringify(out.img)},ex:${JSON.stringify(out.ex)}});\n`);
 const kb=Math.round(fs.statSync(path.join(dir,id+'.js')).size/1024);
 console.log(id,'body',out.body.join(','),'face',out.face&&out.face.join(','),'head top',out.top,'feet',out.foot,'expressions',['n',...Object.keys(out.ex)].join(' '),kb+' KB');
})();
